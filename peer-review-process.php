                        <h4>Peer Review</h4>
                        <p>Each manuscript passing initial plagiarism will be subjected to rigorous and anonymous peer-review by a minimum of 2 peer reviewers. Referees who review a manuscript remain unknown to the authors. The journal’s independent status ensures a submission acceptance rate based on merit and not favour, bias, or personal preference. All the reviewers send the editor a detailed report with their comments on the manuscript and their recommendation. Authors receive reviewers’ recommendation by the editorial staff and they never enter in contact with reviewers. Reviewers have to complete their reviews within 2-3 weeks. For papers which require revision, the editor will make sure that the quality of the revised paper is acceptable.</p>

