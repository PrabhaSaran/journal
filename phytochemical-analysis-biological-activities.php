                 <p> <strong>Abstract :</strong> Alternanthera brasiliana Kuntz is an important herb which is having higher medicinal properties. Through all most all of the parts are used in the traditional system of medicines. The bioactive compounds or phytochemicals present in the plant show many pharmacological activities like wound healing, anti-inflammatory, antitumor, analgesic, immunostimulant and, antimicrobial and antiviral activities. Phytochemical screening of methanolic and ethanolic extracts of, A.brasiliana leaves showed the presence of phenol and alkaloids and A.brasiliana stem extracts showed the presence of different constituents like alkaloids flavonoids steroids glycosides and saponin. The DPPH and ABTS methods were followed for studying antioxidant activities of extracts. The wound healing potential of extracts is determined by the in-vitro method by using chick embryo fibroblast cell line study revealed that both stem and leaf showing wound healing activity. From the extracts the ethanolic extracts showing great wound healing potential at a time interval. Ethanolic stem extracts show comparatively higher wound healing potency. This paves way for future studies on this plant for isolation and commercialization of phytochemicals which are responsible for wound healing property of the plant Alternanthera brasiliana Kuntz.</p>
                    
