                 <p> <strong>Abstract:</strong> Micro-finance is Identified as an effective instrument for mitigating poverty from the environment. Most non-governmental organisations are
able to conduct micro-credit that is considered a “financially viable alternative” and works as the indicator of rural poverty. In this modern
era, the environment becomes at the edge of risk and needs the strong support of financial management. In this regard, the microfinancing
process is one of the effective instruments that is entirely dependent on the philosophy of the group and the pressure of the poor people. It has
been observed based on several records that the concept of micro-finance is able to design financial products based on the requirements of
poor people. In this paper, all the potential pros and cons of microfinance have been mentioned to identify its impact on the environment. In
addition to that, by the identification of the key factors that affect the efficiency of microfinance, the measurement of environmental
sustainability has been done. It needs effective and efficient strategies to enhance the positive effect of microfinance to sustain environmental
growth. In order to analyse the environmental impact of microfinancing in enhancing sustainability all the guidelines have been followed by
the researcher. In this regard, secondary data collection has helped the researcher to find out relevant and useful data and information
about the research topic. The thematic analysis has been used to describe the findings in an understandable way.


