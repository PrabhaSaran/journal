                 <p> <strong>Abstract:</strong> Banks are the most leveraged institutions in the world that have produced protection for the combination of “Federal Deposit Insurance
Corporation (FDIC)” and “fractional-reserve banking”. The primary purpose of this paper is to evaluate the leverage regulations work and
the types of equipment that help in stabilising the financial system. Depending on the leverage ratio an individual bank can measure its total
assets and core capital that help in protecting the bank from any kind of financial or economic crisis. Every individual financial sector
generally follows some specific rules and regulations to maintain the financial flow. In this regard, utilising the microeconomic framework,
the behaviour of banks can be understood. The researcher has selected the “secondary qualitative data collection method” to collect the
data and information to lead the further study. In order to describe the collected sources in an understandable way “thematic technique” has
been adopted. Preparing five themes in simple and understandable words, the paper has been made valuable for the readers. Moreover, this
study paper will serve the readers with reliable and valuable information about leverage regulations work and their impact on the
stabilisation of financial systems.
