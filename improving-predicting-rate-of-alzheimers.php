                 <p> <strong>Abstract:</strong> Recently deep learning has shown a improved performance than machine learning in many of the areas like pattern recognition, image classification computer vision, video segmentation and many more. But out of all these areas, disease classification is one of the major area in which deep learning has shown a remarkable performance than the traditional machine learning algorithms especially in the area of image recognition. Machine learning algorithms are not enough capable to handle the image so in this work we will apply the deep learning approach on the Alzheimer's disease dataset for performing the early detection and classification of the disease and this has done through using neuroimaging data. Previous work done in this area was based on traditional machine learning algorithm and they have used stacked auto encoder (SAC) for dimensionality reduction and they have achieved a classification accuracy of 83.7% during the prediction from initial symptom to final development of Alzheimer's disease. The deep learning algorithm ResNet which is implemented in this paper has shown a classification accuracy of 93% and this is also achieved without applying any dimensionality reduction approach and this has been considered as the best predictive rate on the neuroimaging data till now. The applied ResNet is the improved ResNet and the comparison of both the Resnet models are shown in this work. This deep learning application will also be useful for other types of disease classification like cancer, diabetics, etc.</p>
                    
