                 <p> <strong>Abstract:</strong> Advanced and modern technology has made a revolution in the payment method which has become an extensive payment phenomenon
across the world. This study focuses on the impact of electronic payment systems on customer purchasing behaviour and customer
satisfaction. This study investigates a variety of types of electronic payment systems such as mobile banking, ATM system, internet banking,
and POS system, and how these influence customer satisfaction levels. Electronic payment systems have made the payment method easier
and more flexible. This type of modern technological approach to payment methods has promoted loyalty, delivery service, and customer
satisfaction. In addition to that, e-payment methods are also able to track customers in order to map out the landscape of the future. This
study uses the “primary quantitative data collection method” to make the research paper of better quality and also add value. Along with
this, SPSS software has been used to describe all the findings in an understanding and systematic way. This study concludes that the
e-payment system is cost-effective, reliable, safe, accessible, and easy to transfer money instantly. However, this study also discussed its
issues to make an effective approach to make a better influence on the readers.
