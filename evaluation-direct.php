                 <p> <strong>Abstract:</strong> The economic growth of a country is influenced by several factors and the exchange rate is regarded to be one of them. In the following study,
the direct and indirect effects posed by exchange rates on economic growth have been assessed and elaborated on. The methodology section
consists of suitable and appropriate research methods and techniques which have been used in the study. A secondary qualitative
methodology has been followed for the data collection and analysis processes and a systematic review has been conducted for presenting the
outcomes. Additionally, a thematic analysis has been conducted for evaluating the outcomes of the data collection process. The results of this
study suggest that exchange rates pose both direct and indirect impacts on the economy, however, the indirect impacts are far more diverse
and deeper. It has been observed that exchange rates have an excessive influence on the economy of a country and little changes in exchange
rates are less impactful for the lives of general people. The “fall in the value of exchange rate” is attributed to a Devaluation, which can
drive economic growth as reduced price in foreign exchange rate involves importing expensive and exports cheaper. Therefore, the
outcomes of this study reveal that the indirect effects of exchange rates are more influential on the economic growth of a country.

</p>
          
