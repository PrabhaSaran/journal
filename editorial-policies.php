                                <p>It is a well-known fact that all academic and scholarly manuscripts are composed only after the careful analysis and reviewing of previously published work. As a result, it might be hard to define the borders between definite and distinct plagiarism and permissible referrals. This is why the below-listed guidelines have been formulated to offer a clear idea of how text can be identified and categorized as being plagiarized.</p>
                                <p><strong>The following can be categorized as being plagiarized text -</strong></p>
                                <p>words, sentences, concepts, and research outcomes that have been used without adequate citations, and that are completely identical to someone else's work.</p>

                              <p><span class="glyphicon glyphicon-check" aria-hidden="true"></span>recycling text (also referred to in the industry as self-plagiarism) which involves the use of an author's own work from another publication elsewhere, without any adequate citations and recognition of the original source.</p>
                              <p><span class="glyphicon glyphicon-check" aria-hidden="true"></span>inadequate and scant paraphrasing which involves the lifting of entire paragraphs from another source, without altering the structure of the sentences comprehensively or altering the structure but not replacing words</p>
                              <p><span class="glyphicon glyphicon-check" aria-hidden="true"></span>lifting entire sentences without placing them in quotation marks, and failing to cite the original sources.</p>
                              <p><span class="glyphicon glyphicon-check" aria-hidden="true"></span>offering adequate citations and recognition of original sources, but failing to paraphrase sentences appropriately or placing them within quotation marks is also categorized as involuntary plagiarism. Likewise, text, where sentences are paraphrased in part and quoted in part, are also categorized as involuntary plagiarism. The norm is to either paraphrase such text completely or to place the entire text within quotation marks, while also offering citations of the original sources.</p>
                              <p><span class="glyphicon glyphicon-check" aria-hidden="true"></span>abstract,</p>                                    
                              <p><span class="glyphicon glyphicon-check" aria-hidden="true"></span> introduction,</p>                                    
