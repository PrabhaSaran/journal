                              <p><span class="glyphicon glyphicon-check" aria-hidden="true"></span> conclusion,</p>                                    
<p>are categorized as plagiarized text. This can easily be avoided by paying careful attention to the text and paraphrasing frequently used sentences and using synonyms for frequently used words. Albeit, some technical terms and jargon cannot be altered. The editorial committee of Technoarete Transactions on Advances in Blockchain and Cryptocurrencies is well aware of such complications and will make concessions in these cases.</p>                                
	
