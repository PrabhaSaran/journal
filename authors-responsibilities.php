                        <h3>Standards</h3>
                        <p>Authors of innovative and original research work should present an appropriate account of the results & work performed, followed by a discussion of the scope and importance of the work. Manuscript submitted should contain adequate information and sufficient references to permit others to replicate the work. Review papers should be objective/accurate and comprehensive. Editorial opinion or perspective pieces ought to be clearly identified as such. Misconduct, fraudulent or knowingly inaccurate statements establish unethical concerns and are unacceptable.</p>
                        <h4>Originality & Plagiarism</h4>
                        <p>Authors should confirm that they have written and submitted only original works, and if authors have used another’s words/works has been properly cited. Publications that have been significant in defining the nature of the work described in the manuscript ought to be cited. Plagiarism constitutes unethical publishing takes numerous forms from "passing off" others papers as the author's own, to paraphrasing substantial parts and copying others work (without attribution) and is unacceptable.</p>  
    <h4>Multiple, Duplicate Submission/Publication</h4>
                        <p>Manuscript fundamentally describing the same research should not be published in more than one journal for publication. Henceforth, authors should not submit manuscripts that have already been published for consideration in another journal. Submission of an article/review paper simultaneously to more than one journal constitutes unethical publishing attribution and is unacceptable. Clinical guidelines and translations publication in more than single journal are sometimes justifiable only if certain conditions are met. Authors and editors concerned must decide on secondary publication that should reflect the same data and interpretation of the primary or main document. Reference to the primary document is essential and be cited in the secondary publication.</p>
    <h4>Authorship of the Manuscript</h4>
                        <p>Persons who meet authorship criteria should only be listed as authors in the manuscript. (i) made noteworthy contributions to the conception, design, implementation, data analysis and interpretation, (ii) manuscript preparation/revision as it is critically important for intellectual content; and (iii) thorough observation and approved the final version of the manuscript and approved to its submission for publication. Persons who made significant contributions to the work described in the manuscript (such as writing/technical help/general support and editing assistance) but who do not meet authorship criteria should not be listed as an author. Their contributions towards this have to be acknowledged in the "Acknowledgements" segment only after their written consent to be named. The corresponding author must ensure and verify that all co-authors have seen and approved the final version of the paper and agreed to its submission are included in the authors list for publication.</p>
    <h4>Disclosure & Conflict of Interest</h4>
                        <p>Authors should disclose any conflicts of interest that might influence their interpretation or results in the manuscript. Conflicts of interest that should be revealed include educational grants or other funding, financial ones like honoraria, membership, participation in speakers’ bureaus, consultancies and patent licencing arrangements. Non-financials include professional relationships/knowledge in subject matter or materials discussed in the article. It is highly important to disclose all sources of funding and financial support including the grant number or other reference number. </p>
    <h4>Acknowledgement of Sources</h4>
                        <p>Authors must ensure that they have appropriately acknowledged the work of others, and should also cite publications that have been significant in defining the nature of the reported work. Information gained privately (from correspondence/conversation/discussion with third parties) must not be reported without clear written permission from the source. It is important that authors should not use information obtained in the course of providing confidential services, such as refereeing manuscripts or grant applications, unless they have obtained the explicit written permission of the authors of the work involved in these services.</p>
 
    <h4>Human or Animal </h4>
                        <p>If the work involves the use of animals or human participants, the authors should ensure that all processes and procedures were performed in compliance with relevant laws and institutional guidelines and that the appropriate institutional committee(s) has approved their work. The authors should disclose a statement to this effect in the manuscript. Authors should also include a statement in the manuscript that informed consent was obtained for experimentation with human participants. The privacy rights of human participants must always be observed.</p>

                        
                        
                     
