                 <p class="color-3"><strong>Guidelines for Guest Editors</strong></p>
               
              <p>Special Issues are usually a compilation of articles whose research is based on a common theme that is also relevant and pertinent to the scope and objectives of the TJEIB journal. Special Issues are produced by one or more Guest Editors, who are also assisted by the Editor-in-Chief of the TJEIB journal.</p>
                
                <!-- <p><strong>Generally, a Special Issue is comprised of an assortment of -</strong></p> -->
                
                <div class="focu">
                        <ol>
                            <li> <span class="glyphicon glyphicon-check" aria-hidden="true"></span> A Special Issue is a collection of articles focusing on a theme or themes relevant to the journal’s aims and scope and is often produced by one or more guest editors with the assistance of the journal’s Editor-in-Chief.</li>
                            <li> <span class="glyphicon glyphicon-check" aria-hidden="true"></span> A Special Issue normally consists of a collection of original research papers, review articles and an introduction by the Guest Editors. High quality Special Issues are beneficial to a journal as they have the potential to increase usage and citations and to attract new authors and readers. There is no restriction on the number of papers to be included in the special issue and also on the word limitation/page budget as long as the papers are of high quality. Typically, a Special issue consists of 10-20 articles which can include both research and review papers. If less than 8 papers are accepted, we would still publish them together, but as a Special Section within a regular issue rather than as a standalone Special Issue.</li>
                            <li> <span class="glyphicon glyphicon-check" aria-hidden="true"></span> Guest Editors take the primary responsibility for liaison with contributing authors and peer reviewers. The same review processes and criteria of quality and originality apply to articles in Special Issues as to regular issue articles. All papers accepted for publication (except Editorials) should be peer reviewed by at least two independent referees.</li>
                            <li> <span class="glyphicon glyphicon-check" aria-hidden="true"></span> Potential Guest Editor(s) who would like to propose a thematic Special Issue are invited to prepare a proposal that would outline the nature of the proposed issue; how the Issue fits with the scope of the journal; why it is necessary and how it has the potential to add to and challenge existing knowledge; any novelty provided by the papers; and if the special issue is derived from a conference, please detail any other special issues from the same conference that are planned or already approved. The proposal should also include: potential areas for authors to consider, potential contributors, titles and complete Guest Editors’ details with a timetable for recorded peer-reviewing, revision and transmittal in the format required for publication. Besides, potential guest editors can also provide details of their editorial and reviewing experience. All proposals are evaluated by Journal Editors. Once a proposal has been reviewed the Guest Editor will be sent a letter either accepting or rejecting the proposal.</li>
                    </ol>
