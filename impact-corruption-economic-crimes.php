                 <p> <strong>Abstract:</strong> The main aim of this study is to assess and compare the quality of audit disclosure between developing and developed countries. Regarding
this, relevant methods and procedures have been followed for collecting and evaluating secondary qualitative data associated with the
research phenomenon. An interpretivism research philosophy along with an exploratory research design has been used for guiding the
research methods and procedures. The results of this study have revealed that the regulatory framework, auditing practices and activities
are different in developed and emerging countries. The main factors that influence audit quality are effective optimisation and regulation by
the government and business firms. Additionally, business firms are responsible for providing proper details and information associated with
their “financial statements” and costing for reflecting their “financial performance” and position in the market. The governments of both
developed and emerging economies have adopted effective regulations and legislations for ensuring proper disclosure of “audit reports”
and “financial statements”. Due to the differences in these aspects and the practice associated with auditing, including auditing format,
pricing and other activities, the quality of “audit disclosure” is also different among developing and developed countries. Apart from this,
the maintenance of “audit quality” involves various aspects, such as legislation and government regulations.
