                 <p> <strong>Abstract :</strong>  Background: globally the existence of the midwifery profession is needed by a wide range of stakeholders. The midwife profession has been proven to be able to change discipline and leadership in the world of health. Independent Practice Midwives (PMB) becomes one of the basic health facilities engaged in the field of women's health in which requires the management of health management. </p>
               
                <p> <strong>Methods :</strong> this type of research uses descriptive quantitative methods to look at the management of the Independent Practice system of Midwives Bekti, Kulon Progo. The populations in this study are all officers who are registered as employees. Samples are being used in this study determined by accidental sampling, namely employees who were found to be at work at the time of the research was carried out, as well as the founder of PMB. </p>
               <p> <strong>Results :</strong> building requirements, space and infrastructure can be known that the percentage number that has met the standard as much as 95% and 5% of them that do not meet the fire extinguisher (APAR) is not available in ready-made conditions. The percentage of employee indicators has met as much as 100%. The entire process of each examination is recorded in the patient's Medical Record (RM) in the form of a book or hard copy. The types of services provided include ANC (Antenatal Care), Ultrasound, pregnant women, maternity, post-partum and infants, MTBS (Integrated Management of Sick Toddlers), family planning for pills, injections, implants, Intrauterine Device, simple Emergency Unit services, infant massage and immunization.</p>
               <p> <strong>Conclusion :</strong> Organizational Management in PMB Bekti Kulon Progo has fulfilled the requirements rules in the implementation of Standards of Midwifery Services and permenkes RI Number 28 Year 2017 on the License of Midwife Practice Implementation but in the use of ambulances are still not in accordance with health standards.</p>
               
                    
