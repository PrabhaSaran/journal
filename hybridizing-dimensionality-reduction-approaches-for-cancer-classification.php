                 <p> <strong>Abstract:</strong> In the DNA microarray datasets, genes expression has made a big impact on the classification of diseases especially in the case of tumor classification. Tumor classification is basically done to predict the cancer on the basis of genes expression profile. Although genes expression dataset are considered to be high dimensional dataset, so dimensionality reduction is very much needed during the classification. In this work to reduce the dimension of genes expression we have proposed the hybrid approach using ReliefF method and the genetic algorithm. The combination of these methods will be used for selecting the subset of the genes before performing the classification. In this work ReliefF method and genetic algorithm will work as a filter method and wrapper method respectively and there combination will form the hybrid method. The results have shown that the proposed work can be implemented on the genes expression dataset to improve the classification accuracy during the disease prediction. The proposed work has computed the classification accuracy of 94.4%, 96.7%, 96.6% and 90.6% on genes expression of Colon cancer, Leukemia, lung and prostate respectively. </p>
                   
