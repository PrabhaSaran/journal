                      <h4>General</h4>
                        
                       <p> Manuscripts submitted to the Technoarete Journal on Accounting and Finance journal must be written in English. Papers accepted for publication vary from 5 to 12 pages in Single column format. The main text usually can be divided into separate sections, organized by Introduction, Materials and Methods, Results, Discussion, Conclusion.</p>

                        <hr>
                        <h4>Paper Title</h4>
                        <p>A title of no more than 20 words should be brief, specific, and informative.</p>
<hr>
    <h4>Author Details</h4>
                        <p>Full name for all authors should be given; The names of multiple authors are separated by a comma; Provide the full affiliation for each author including academic affiliation, city, country, e-mail; If multiple authors have contributed to the article, details of the corresponding author should be clear. Email address is compulsory for the corresponding author.</p>
<hr>
    <h4>Abstract</h4>
                        <p>The abstract should be written as a continuous paragraph with 200-250 words and recapitulative state the background of the research, purpose, methodologies, principal results, major conclusions and its contributions to the field. It should emphasize new or important aspects of the study.</p>
<hr>
    <h4>Keywords</h4>
                        <p>Include 3–10 keywords or short phrases for indexing</p>
                     <hr>   
                        
   <h4> Introduction</h4>
                        <p>Provide a brief overview of the scope and relevance of the research, especially with regard to previous advancements in related fields</p>
<hr>
    <h4>Materials and Methods</h4>
                        <p>Present the research design, research type, research duration, inclusion/exclusion criteria, choice of subjects, etc. Describe the methodology completely, including sample collection, processing, lab analysis, statistical tests used for data analysis etc. Use section headings/subheadings in a logical order to entitle each category or method . (e.g. 1, 2; 1.1, 2.1; 1.1.1, 2.1.1…etc)</p>
<hr>
                        <h4>Results</h4>
                        <p>Present and illustrate your findings objectively and concisely, if appropriate, with figures/ tables. In the main text, describe each of your results by a particular observation.</p>
<hr>
    <h4>Discussion</h4>
                        <p>Provide an interpretation of your results and make comparisons with other studies. The significance of findings should be clearly described. If your results differ from your expectations, explain why that may have happened. If your results agree, then describe the theory that the evidence supported.</p>
<hr>
    <h4>Conclusion</h4>
                        <p>The main conclusions of the experimental work should be presented. The contribution of the work to the scientific research and its economic implications should be emphasized.</p>

